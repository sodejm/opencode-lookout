/** Compile Solid JSX before npm installation; OpenTUI does not transform node_modules. */
import { transformAsync } from "@babel/core";
import { readFile, writeFile, mkdir } from "node:fs/promises";

const result = await transformAsync(await readFile("src/tui.tsx", "utf8"), {
  filename: "src/tui.tsx",
  configFile: false,
  babelrc: false,
  sourceMaps: false,
  presets: [
    [
      "babel-preset-solid",
      { moduleName: "@opentui/solid", generate: "universal" },
    ],
    "@babel/preset-typescript",
  ],
  plugins: [
    () => ({
      visitor: {
        /** @param {import('@babel/core').NodePath<import('@babel/core').types.ImportDeclaration>} path Import to relocate beside the original source modules. */
        ImportDeclaration(path) {
          const source = path.node.source;
          if (source.value.startsWith("./")) {
            source.value = "../src/" + source.value.slice(2);
            if (!/\.(?:mjs|ts)$/.test(source.value)) source.value += ".ts";
          }
        },
      },
    }),
  ],
});
if (!result?.code) throw new Error("TUI compilation produced no code");
const output =
  "// Generated by npm run build; do not edit.\n" + result.code + "\n";
if (process.argv[2] === "--write") {
  await mkdir("dist", { recursive: true });
  await writeFile("dist/tui.js", output);
} else if ((await readFile("dist/tui.js", "utf8")) !== output) {
  throw new Error(
    "Compiled TUI is stale; run npm run build and review the diff",
  );
}
console.log("PASS compiled TUI matches source");
